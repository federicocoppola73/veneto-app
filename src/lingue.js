// Testo nella lingua scelta, con ripiego sull'italiano
export const testoLingua = (lingua, oggetto) => {
  if (!oggetto) return '';
  if (typeof oggetto === 'string') return oggetto;
  return oggetto[lingua] || oggetto.it || '';
};
