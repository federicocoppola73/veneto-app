// Restituisce una funzione t('chiave') per la lingua scelta
export function traduttore(lingua) {
  const tabella = TESTI[lingua] || TESTI[LINGUA_PREDEFINITA];
  // i testi nominano Venezia: nelle altre città si usa il nome della città attiva
  const nome = nomeCitta();
  const adatta = (testo) => (nome === 'Venezia' || typeof testo !== 'string' ? testo : testo.replace(/Venezia|Venice/g, nome));
  // alcune voci hanno un testo diverso fuori da Venezia
  const ALTERNATIVE = { srv_vaporetto: 'srv_mezzi', cat_piazze: 'cat_piazze_citta' };
  const chiaveAdatta = (k) => (nome !== 'Venezia' && ALTERNATIVE[k] ? ALTERNATIVE[k] : k);
  return (chiave) => adatta(tabella[chiaveAdatta(chiave)] ?? TESTI[LINGUA_PREDEFINITA][chiaveAdatta(chiave)] ?? chiave);
}

// Prende il testo nella lingua scelta da un campo multilingua del JSON
export function testoLocalizzato(campo, lingua) {
  if (!campo) return '';
  if (typeof campo === 'string') return campo;
  return campo[lingua] || campo[LINGUA_PREDEFINITA] || Object.values(campo)[0] || '';
}

// Lingua del telefono, se è tra quelle supportate
export function linguaDelDispositivo() {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale || '';
    const codice = locale.slice(0, 2).toLowerCase();
    return LINGUE.some((l) => l.codice === codice) ? codice : LINGUA_PREDEFINITA;
  } catch {
    return LINGUA_PREDEFINITA;
  }
}
